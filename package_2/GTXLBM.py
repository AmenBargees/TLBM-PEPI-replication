def collision_MRT_py():
    global rho, u, f, tau_f, Mi, Mi_S, S_, w, shifted_distribution

    m_eq    = np.zeros((ny_i,nz_i,na,nx_i),dtype=np_float)
    if D == 2:
        jx      = rho * u[:,:,X,:]
        jy      = rho * u[:,:,Y,:]
        jx2     = jx * jx
        jy2     = jy * jy
        j2      = jx2 + jy2
        threej2 = 3 * j2
        m_eq[:,:,0,:] = rho
        m_eq[:,:,1,:] = -2 * rho + threej2
        m_eq[:,:,2,:] = rho - threej2
        m_eq[:,:,3,:] =   jx
        m_eq[:,:,4,:] = - jx
        m_eq[:,:,5,:] =   jy
        m_eq[:,:,6,:] = - jy
        m_eq[:,:,7,:] =   jx2 - jy2
        m_eq[:,:,8,:] =   jx  *  jy
    elif D == 3:
        jx       = rho * u[:,:,X,:]
        jy       = rho * u[:,:,Y,:]
        jz       = rho * u[:,:,Z,:]
        jx2      = jx * jx
        jy2      = jy * jy
        jz2      = jz * jz
        j2       = jx2 + jy2 + jz2
        m_eq[:,:, 0,:] = rho
        m_eq[:,:, 1,:] = -11 * rho + 19  * j2
        m_eq[:,:, 2,:] = 3 * rho   - 5.5 * j2
        m_eq[:,:, 3,:] = jx
        m_eq[:,:, 4,:] = -0.66666666666667 * jx
        m_eq[:,:, 5,:] = jy
        m_eq[:,:, 6,:] = -0.66666666666667 * jy
        m_eq[:,:, 7,:] = jz
        m_eq[:,:, 8,:] = -0.66666666666667 * jz
        m_eq[:,:, 9,:] = 2 * jx2 - jy2 - jz2
        m_eq[:,:,10,:] = -(0.5) * m_eq[:,:,9,:]
        m_eq[:,:,11,:] = jy2 - jz2
        m_eq[:,:,12,:] = -(0.5) * (jy2 - jz2)
        m_eq[:,:,13,:] = jx * jy
        m_eq[:,:,14,:] = jy * jz
        m_eq[:,:,15,:] = jx * jz
        m_eq[:,:,16,:] = 0
        m_eq[:,:,17,:] = 0
        m_eq[:,:,18,:] = 0

    m       = np.zeros((ny_i,nz_i,na,nx_i),dtype=np_float)
    for a in range(na):
        for b in range(na):
            if shifted_distribution:
                m[:,:,a,:] += M[a,b] * (f[:,:,b,:]+w[b])
            else:
                m[:,:,a,:] += M[a,b] *  f[:,:,b,:]

    Delta_m = m_eq - m
    omega = 1/tau_f         # This gets the desired viscosity
    Delta_f = np.zeros((ny_i,nz_i,na,nx_i),dtype=np_float)
    for a in range(na):
        for b in range(na):
            if D == 2:
                if b < 7:
                    Delta_f[:,:,a,:] += (Mi_S[a,b] * Delta_m[:,:,b,:])
                else:
                    Delta_f[:,:,a,:] += (Mi[a,b] * omega * Delta_m[:,:,b,:])
            elif D == 3:
                if b < 9 or b == 10 or b == 12 or b > 15:
                    Delta_f[:,:,a,:] += (Mi_S[a,b] * Delta_m[:,:,b,:])
                else:
                    Delta_f[:,:,a,:] += (Mi[a,b] * omega  * Delta_m[:,:,b,:])
    return Delta_f

