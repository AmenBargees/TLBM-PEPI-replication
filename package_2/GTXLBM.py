#-------------------------------------------------------------------------------
# Density from melt for different rock types
#-------------------------------------------------------------------------------

def calculate_melt_extraction(rock, M, M0, M1, M2, M3, M4, cumulative_extracted):

    M_ext                 = ((M - M1) * ((M > M2) & (M < M3)))
    mask                  = M_ext >= 0           # make sure melt extract is not negative
    cumulative_extracted += (M_ext*mask)

    cumulative_extracted  = np.where(cumulative_extracted < M4, cumulative_extracted, M4)
    M                     = mask_melt*(M0 - cumulative_extracted * (M0 > cumulative_extracted))

    check_cumulative_extract = False
    if it%Inc_data == 0 and check_cumulative_extract:
        print_field_range("t_p = %d, rock = %s, M      " %(it,rock),M)
        print_field_range("t_p = %d, rock = %s, cum_ext" %(it,rock),cumulative_extracted)

    return M, cumulative_extracted

#-------------------------------------------------------------------------------
# Calculate density based on the rock type and cumulative extracted melt
#-------------------------------------------------------------------------------

def calculate_density(rock,rho0,rho,T,P,M,cumulative_extracted):

#   Melt density (Talas Gerya 2015 nature)

#   Note: the divisiions by rho_bar ensure that even if the mean lattice density gradually
#   grows during a simulation (eg. due to roundoff), only the fluctuations in lattice
#   density will have an effect on the calculated density = rho0 * [1+ (fluctuations in lattice density)]
#   where rho0 is the initialized density profile

    rho_melt = 2900 * rho/rho_bar

    if rock == "peridotite":

        coef_res    = np.where(cumulative_extracted<M4_pd,-0.04*cumulative_extracted,M4_pd)
        coef_phase  = 0
        rho_solid   = (rho0 * rho/rho_bar * (1 - 0.04 * cumulative_extracted))
        rho_eff     = (rho_solid  * (1 - M) + rho_melt*M             )

